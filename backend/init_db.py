import sys
import os

# Add parent directory to path so we can import backend
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from backend.database import get_db_connection

def create_complaints_table():
    conn = get_db_connection()
    cursor = conn.cursor()
    
    try:
        # Check if table exists
        cursor.execute("SELECT count(*) FROM user_tables WHERE table_name = 'COMPLAINTS'")
        if cursor.fetchone()[0] == 0:
            print("Creating COMPLAINTS table...")
            cursor.execute("""
            CREATE TABLE COMPLAINTS (
                COMPLAINT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                C_ID VARCHAR2(50),
                MESSAGE_CONTEXT CLOB,
                ISSUE_TYPE VARCHAR2(100),
                ISSUE_NOTES CLOB,
                STATUS VARCHAR2(20) DEFAULT 'OPEN',
                CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
            """)
            conn.commit()
            print("Table created successfully!")
        else:
            print("COMPLAINTS table already exists.")
            
    except Exception as e:
        print(f"Error creating table: {e}")
    finally:
        cursor.close()
        conn.close()

if __name__ == "__main__":
    create_complaints_table()
